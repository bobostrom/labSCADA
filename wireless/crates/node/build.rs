use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct EquipmentManifest {
    #[serde(default)]
    wireless_nodes: Vec<WirelessNodeConfig>,
}

#[derive(Debug, Deserialize)]
struct WirelessNodeConfig {
    slot: u8,
    key: String,
    #[serde(default = "default_report_interval")]
    report_interval_secs: u64,
    #[serde(default)]
    calibration: Option<CalibrationConfig>,
    #[serde(default)]
    probe_roms: Option<[String; 3]>,
}

fn parse_rom_hex(raw: &str) -> [u8; 8] {
    let hex: String = raw
        .chars()
        .filter(|c| !matches!(c, ':' | '-' | '_' | ' '))
        .collect();
    assert!(
        hex.len() == 16,
        "Invalid 1-Wire ROM '{raw}': expected 16 hex chars (8 bytes)"
    );
    let mut out = [0u8; 8];
    for (i, byte) in out.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16)
            .unwrap_or_else(|e| panic!("Invalid hex in 1-Wire ROM '{raw}': {e}"));
    }
    out
}

fn default_report_interval() -> u64 {
    20
}

#[derive(Debug, Deserialize)]
struct CalibrationConfig {
    battery_scale_num: u32,
    battery_scale_den: u32,
}

struct SlotDefaults {
    prefix: &'static str,
    comment: &'static str,
    slot: u8,
    key: &'static str,
}

const SLOTS: &[SlotDefaults] = &[
    SlotDefaults {
        prefix: "DEWAR",
        comment: "Slot 1: Dewar Node",
        slot: 1,
        key: "dewar_node_01",
    },
    SlotDefaults {
        prefix: "FRIDGE",
        comment: "Slot 2: Medical Cold Storage Node",
        slot: 2,
        key: "cold_storage_node_01",
    },
    SlotDefaults {
        prefix: "DEWAR3",
        comment: "Slot 3: Dewar #3 Plain RTD Node",
        slot: 3,
        key: "dewar3_node_01",
    },
];

fn format_rom_array(rom: &[u8; 8]) -> String {
    format!(
        "[0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X}]",
        rom[0], rom[1], rom[2], rom[3], rom[4], rom[5], rom[6], rom[7]
    )
}

fn resolve_slot_values(
    manifest: &EquipmentManifest,
    spec: &SlotDefaults,
) -> (u64, u32, u32, Option<[[u8; 8]; 3]>) {
    let mut interval = default_report_interval();
    let mut cal_num = 4072u32;
    let mut cal_den = 2014u32;
    let mut probe_roms = None;

    if let Some(node) = manifest
        .wireless_nodes
        .iter()
        .find(|n| n.slot == spec.slot || n.key == spec.key)
    {
        interval = node.report_interval_secs;
        if let Some(cal) = &node.calibration {
            cal_num = cal.battery_scale_num;
            cal_den = cal.battery_scale_den;
        }
        if let Some(roms) = &node.probe_roms {
            probe_roms = Some([
                parse_rom_hex(&roms[0]),
                parse_rom_hex(&roms[1]),
                parse_rom_hex(&roms[2]),
            ]);
        }
    }

    (interval, cal_num, cal_den, probe_roms)
}

fn main() {
    let site = env::var("LABSCADA_SITE").unwrap_or_else(|_| "demo".to_string());
    println!("cargo:rerun-if-env-changed=LABSCADA_SITE");

    // Locate manifest relative to crate directory: ../../../sites/<site>/equipment.json
    let crate_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let manifest_path = PathBuf::from(&crate_dir)
        .join("../../../sites")
        .join(&site)
        .join("equipment.json");

    println!("cargo:rerun-if-changed={}", manifest_path.display());

    let content = fs::read_to_string(&manifest_path)
        .unwrap_or_else(|_| panic!("Failed to read equipment manifest at {:?}", manifest_path));

    let manifest: EquipmentManifest = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("Failed to parse equipment manifest JSON at {:?}: {}", manifest_path, e));

    let mut code = format!(
        "// Auto-generated by build.rs from equipment.json (site: {site}) — DO NOT EDIT\npub const SITE_NAME: &str = \"{site}\";\n"
    );

    for spec in SLOTS {
        let (interval, num, den, probe_roms) = resolve_slot_values(&manifest, spec);
        let rom_expr = match probe_roms {
            Some(roms) => format!(
                "Some([{}, {}, {}])",
                format_rom_array(&roms[0]),
                format_rom_array(&roms[1]),
                format_rom_array(&roms[2]),
            ),
            None => "None".to_string(),
        };
        let _ = write!(
            code,
            "\n// {comment}\npub const {p}_SLOT: u8 = {slot};\npub const {p}_REPORT_INTERVAL_SECS: u64 = {interval};\npub const {p}_BATT_CAL_NUM: u32 = {num};\npub const {p}_BATT_CAL_DEN: u32 = {den};\npub const {p}_PROBE_ROMS: Option<[[u8; 8]; 3]> = {rom_expr};\n",
            comment = spec.comment,
            p = spec.prefix,
            slot = spec.slot,
        );
    }

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("node_config.rs");
    fs::write(&dest_path, code).unwrap();
}
