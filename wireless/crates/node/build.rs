use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct EquipmentManifest {
    #[serde(default)]
    wireless_nodes: Vec<WirelessNodeConfig>,
}

#[derive(Debug, Deserialize)]
struct WirelessNodeConfig {
    slot: u8,
    key: String,
    #[serde(default = "default_report_interval")]
    report_interval_secs: u64,
    #[serde(default)]
    calibration: Option<CalibrationConfig>,
}

fn default_report_interval() -> u64 {
    20
}

#[derive(Debug, Deserialize)]
struct CalibrationConfig {
    battery_scale_num: u32,
    battery_scale_den: u32,
}

fn main() {
    let site = env::var("LABSCADA_SITE").unwrap_or_else(|_| "demo".to_string());
    println!("cargo:rerun-if-env-changed=LABSCADA_SITE");

    // Locate manifest relative to crate directory: ../../../sites/<site>/equipment.json
    let crate_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let manifest_path = PathBuf::from(&crate_dir)
        .join("../../../sites")
        .join(&site)
        .join("equipment.json");

    println!("cargo:rerun-if-changed={}", manifest_path.display());

    let content = fs::read_to_string(&manifest_path)
        .unwrap_or_else(|_| panic!("Failed to read equipment manifest at {:?}", manifest_path));

    let manifest: EquipmentManifest = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("Failed to parse equipment manifest JSON at {:?}: {}", manifest_path, e));

    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("node_config.rs");

    let mut dewar_num = 4072u32;
    let mut dewar_den = 2014u32;
    let mut dewar_interval = 20u64;

    let mut fridge_num = 4072u32;
    let mut fridge_den = 2014u32;
    let mut fridge_interval = 20u64;

    for node in manifest.wireless_nodes {
        if node.slot == 1 || node.key == "dewar_node_01" {
            dewar_interval = node.report_interval_secs;
            if let Some(cal) = node.calibration {
                dewar_num = cal.battery_scale_num;
                dewar_den = cal.battery_scale_den;
            }
        } else if node.slot == 2 || node.key == "cold_storage_node_01" {
            fridge_interval = node.report_interval_secs;
            if let Some(cal) = node.calibration {
                fridge_num = cal.battery_scale_num;
                fridge_den = cal.battery_scale_den;
            }
        }
    }

    let code = format!(
        r#"// Auto-generated by build.rs from equipment.json (site: {site}) — DO NOT EDIT
pub const SITE_NAME: &str = "{site}";

// Slot 1: Dewar Node
pub const DEWAR_SLOT: u8 = 1;
pub const DEWAR_REPORT_INTERVAL_SECS: u64 = {dewar_interval};
pub const DEWAR_BATT_CAL_NUM: u32 = {dewar_num};
pub const DEWAR_BATT_CAL_DEN: u32 = {dewar_den};

// Slot 2: Medical Cold Storage Node
pub const FRIDGE_SLOT: u8 = 2;
pub const FRIDGE_REPORT_INTERVAL_SECS: u64 = {fridge_interval};
pub const FRIDGE_BATT_CAL_NUM: u32 = {fridge_num};
pub const FRIDGE_BATT_CAL_DEN: u32 = {fridge_den};
"#
    );

    fs::write(&dest_path, code).unwrap();
}

